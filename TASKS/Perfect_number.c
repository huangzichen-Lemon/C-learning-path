/*题面描述：
魔法世界有一个毕达哥拉斯学派，他们把一个数称为“完美数”，如果该数恰好等于它的因子之和。他们认为完美数具有神奇的魔力。如6的因子为1、2、3，而 6＝1＋2＋3，因此6是“完美数”。创始人毕达哥拉斯说：“6象征着完满的婚姻以及健康和美丽，因为它的部分是完整的，并且其和等于自身。”
perfect.png
请找出给定范围中的完美数。
输入：
两个正整数m和n，以空格间隔，为指定的范围（包括m和n，m和n均不超过100000）。

输出：
在单行中输出给定范围内的所有完美数，每个完美数占一行。每个完美数的后面为一个冒号，然后由小到大输出它的因子，每个因子之后跟着一个空格，最后换行。

示例输入：
1 6

示例输出：
1: 1
6: 1 2 3*/
#include <stdio.h>
int main()
{
    int m, n, temp, i, t, c = 0;

    scanf("%d %d", &m, &n);

    if (m > n)
    {
        temp = m;
        m = n;
        n = temp;
    }
    int s[n];
    for (i = m; i <= n; i++)
    {
        for (t = 0; t <= n - 1; t++)
        {
            s[t] = 0;
        }
        c = 0;
        for (t = 1; t < i; t++)
        {
            if (i % t == 0)
                s[t] = t;
        }
        for (t = 1; t <= i - 1; t++)
            c += s[t];
        if (c == i)
        {
            printf("%d: ", i);
            for (t = 1; t <= i - 1; t++)
            {
                if (s[t] != 0)
                    printf("%d ", s[t]);
            }
            printf("\n");
        }
        else if (i == 1)
        {
            printf("1: 1\n");
        }
        for (t = 0; t <= n - 1; t++)
        {
            s[t] = 0;
        }
    }
    return 0;
}