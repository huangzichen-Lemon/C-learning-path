/*题面描述：
九九乘法表又称九九乘法歌诀，在《荀子》、《管子》、《淮南子》、《战国策》等中国古书中就能找到“三九二十七”、“六八四十八”、“四八三十二”、“六六三十六”等句子。试编程输出九九乘法表中指定范围的部分。
99.png

输入：
三个整数m、s和n，表示指定的范围。m和s表示起始值，n表示输出个数。保证输入合法。

输出：
乘法表中指定的部分见输出示例。

示例输入：
1 3 10

示例输出：
1*3=3
1*4=4
1*5=5
1*6=6
1*7=7
1*8=8
1*9=9
2*3=6
2*4=8
2*5=10
*/
#include <stdio.h>
int main(void)
{
    int i, t, m, s, n;
    scanf("%d %d %d", &m, &s, &n);
    for (i = m; i < m + (n / (9 - s + 1)); i++)
    {
        for (t = s; t <= 9; t++)
            printf("%d*%d=%d\n", i, t, i * t);
    }
    for (t = s; t < s + n % (9 - s + 1); t++)
    {
        i = n / (9 - s + 1) + m;
        printf("%d*%d=%d\n", i, t, i * t);
    }
    return 0;
}
