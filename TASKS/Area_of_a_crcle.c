/*题面描述：
如图所示，魔法学院计划建设一个圆形广场，圆的半径r为整数，现要求圆的面积大于指定的值，则最小的面积是多少。
circle.png

输入：
一个数N，为要求建设圆的面积最小值。

输出：
标准输出，实际圆面积的最小值，小数点后保留两位。
示例输入：
5.1

示例输出：
12.57*/
#include <stdio.h>
int main(void)
{
    int i = 1;
    double a = 0.0, pi = 3.141592653589793;
    double n;
    scanf("%lf", &n);
    while (a <= n)
    {
        a = pi * i * i;
        i++;
    }
    printf("%.2f\n", a);
    return 0;
}
