/*任务3】统计比赛成绩排名
有n位选手参加射击比赛，每位选手有m次机会，写一个程序，输入n、m的值，并输入每位选手每次射击的分数，然后计算和显示每位选手的总分，输出第几位选手是冠军，分数是多少。假设每个选手分数如下：

第1位选手   9.6  6.7  9.9

第2位选手   8.6  7.8  7.9

第3位选手   9.8  9.7  8.9

第4位选手   9.6  8.7  9.9

第5位选手   6.6  7.7  7.9

实验步骤与要求：

    （1）使用嵌套循环，不限使用哪个循环语句

（2）每行输出选手序号和该选手总分

（3）最后一行显示冠军序号和总分

（4）暂时不使用数组*/

#include <stdio.h>
int main(void)
{
    int m, n, i, t;
    float temp1 = 0.0, temp2 = 0.0;
    int temp3 = 0;
    scanf("%d%d", &n, &m);
    for (i = 1; i <= n; i++)
    {
        float a = 0.0;
        for (t = 1; t <= m; t++)
        {

            scanf("%f", &temp1);
            a += temp1;
        }
        printf("第%d位同学的成绩是%.1f\n", i, a);
        if (a >= temp2)
        {
            temp2 = a;
            temp3 = i;
        }
    }
    printf("最高分的是第%d位同学，分数是%.1f", temp3, temp2);
    return 0;
}