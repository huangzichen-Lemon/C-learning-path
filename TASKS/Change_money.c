/*题面描述：
把N元钱换成10元、5元、1元这样的零钱，在这三种零钱中每种零钱都至少各有一张的情况下，共有多少种兑换方案（16≤N≤105）

输入：
标准输入，一个整数Ｎ。

输出：
输出方案数。

示例输入：
100

示例输出：
81*/
#include <stdio.h>
int main()
{
    int n, t1, t2, i, t, num = 0;
    scanf("%d", &n);
    t1 = n / 10;
    for (i = 1; i <= t1; i++)
    {
        t2 = (n - i * 10) / 5;

        {
            for (t = 1; t <= t2; t++)
                if ((i * 10 + t * 5) != n)
                    num++;
        }
    }
    printf("%d", num);
    return 0;
}
